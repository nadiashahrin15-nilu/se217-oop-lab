public class DataTypes {
    public static void main(String[] args) {
        int a = 100;
        long b = 100000L;
        float c = 10.5f;
        double d = 20.55;
        boolean e = true;
        char f = 'A';

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}